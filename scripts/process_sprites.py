#!/usr/bin/env python3
"""
Slices the 3 raw 1536x1024 (3x2 grid) pixel-art sprite sheets generated by Azure GPT-Image-2.5
into individual, clean, bottom-aligned, transparent PNG sprites in Sources/WestieDeskPet/Resources/Sprites/.
"""
from __future__ import annotations

import argparse
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image


def keep_largest_component(mask: np.ndarray) -> np.ndarray:
    """Keep only the largest 8-connected opaque component (strips stray sparks/extra balls)."""
    h, w = mask.shape
    visited = np.zeros_like(mask, dtype=bool)
    best_coords: list[tuple[int, int]] = []

    ys, xs = np.where(mask)
    for sy, sx in zip(ys.tolist(), xs.tolist()):
        if visited[sy, sx]:
            continue
        comp: list[tuple[int, int]] = []
        q: deque[tuple[int, int]] = deque([(sy, sx)])
        visited[sy, sx] = True
        while q:
            cy, cx = q.popleft()
            comp.append((cy, cx))
            for ny in (cy - 1, cy, cy + 1):
                if ny < 0 or ny >= h:
                    continue
                for nx in (cx - 1, cx, cx + 1):
                    if 0 <= nx < w and not visited[ny, nx] and mask[ny, nx]:
                        visited[ny, nx] = True
                        q.append((ny, nx))
        if len(comp) > len(best_coords):
            best_coords = comp

    cleaned = np.zeros_like(mask, dtype=bool)
    for cy, cx in best_coords:
        cleaned[cy, cx] = True
    return cleaned


def clean_and_normalize_sprite(
    cell_img: Image.Image,
    canvas_size: int = 128,
    bottom_align: bool = True,
    padding: int = 8,
    fixed_scale: float | None = None,
    largest_only: bool = True,
) -> tuple[Image.Image, float]:
    rgba = np.array(cell_img.convert("RGBA"))
    alpha = rgba[:, :, 3]

    # Trim 4px outer cell border & remove faint semi-transparent dust (< 45 alpha)
    mask = alpha >= 45
    mask[:4, :] = False
    mask[-4:, :] = False
    mask[:, :4] = False
    mask[:, -4:] = False

    if largest_only and np.any(mask):
        mask = keep_largest_component(mask)

    rgba[~mask] = [0, 0, 0, 0]

    ys, xs = np.where(mask)
    if len(xs) == 0 or len(ys) == 0:
        return Image.new("RGBA", (canvas_size, canvas_size), (0, 0, 0, 0)), 1.0

    x0, x1 = int(xs.min()), int(xs.max()) + 1
    y0, y1 = int(ys.min()), int(ys.max()) + 1

    cropped = Image.fromarray(rgba[y0:y1, x0:x1], mode="RGBA")
    cw, ch = cropped.size

    target_max = canvas_size - padding * 2
    auto_scale = min(target_max / cw, target_max / ch)
    scale = min(fixed_scale, auto_scale) if fixed_scale is not None else auto_scale

    new_w = max(1, int(round(cw * scale)))
    new_h = max(1, int(round(ch * scale)))

    # Nearest-neighbor keeps pixel art crisp!
    resized = cropped.resize((new_w, new_h), resample=Image.Resampling.NEAREST)

    out = Image.new("RGBA", (canvas_size, canvas_size), (0, 0, 0, 0))
    paste_x = (canvas_size - new_w) // 2
    if bottom_align:
        paste_y = canvas_size - new_h - 4
    else:
        paste_y = (canvas_size - new_h) // 2

    out.paste(resized, (paste_x, paste_y), resized)
    return out, auto_scale


def slice_grid_3x2(
    sheet_path: Path,
    mapping: list[tuple[int, int, str, int, bool, bool]],
    out_dir: Path,
) -> None:
    sheet = Image.open(sheet_path).convert("RGBA")
    sw, sh = sheet.size
    col_w = sw // 3
    row_h = sh // 2

    out_dir.mkdir(parents=True, exist_ok=True)
    ref_scale: float | None = None

    for col, row, name, canvas_size, bottom_align, lock_ref_scale in mapping:
        box = (col * col_w, row * row_h, (col + 1) * col_w, (row + 1) * row_h)
        cell = sheet.crop(box)
        sprite, used_scale = clean_and_normalize_sprite(
            cell,
            canvas_size=canvas_size,
            bottom_align=bottom_align,
            fixed_scale=ref_scale if lock_ref_scale else None,
        )
        if ref_scale is None and lock_ref_scale:
            ref_scale = used_scale
        dest = out_dir / f"{name}.png"
        sprite.save(dest)
        print(f"[SPRITE] Saved {dest.name} ({canvas_size}x{canvas_size}, scale={used_scale:.3f})")


def main() -> None:
    parser = argparse.ArgumentParser(description="Slice raw sprite sheets into normalized game PNGs")
    parser.add_argument(
        "--raw-dir",
        default=str(Path(__file__).resolve().parent.parent / "assets_raw"),
    )
    parser.add_argument(
        "--out-dir",
        default=str(
            Path(__file__).resolve().parent.parent
            / "Sources"
            / "WestieDeskPet"
            / "Resources"
            / "Sprites"
        ),
    )
    args = parser.parse_args()
    raw_dir = Path(args.raw_dir)
    out_dir = Path(args.out_dir)

    slice_grid_3x2(
        raw_dir / "westie_companion_sheet.png",
        [
            (0, 0, "westie_idle", 128, True, True),
            (1, 0, "westie_walk_1", 128, True, True),
            (2, 0, "westie_walk_2", 128, True, True),
            (0, 1, "westie_sit_tilt", 128, True, True),
            (1, 1, "westie_sleep", 128, True, True),
            (2, 1, "westie_dangling", 128, False, False),
        ],
        out_dir,
    )

    slice_grid_3x2(
        raw_dir / "westie_tennis_sheet.png",
        [
            (0, 0, "westie_holding_ball", 128, True, True),
            (1, 0, "westie_tennis_ready", 128, True, True),
            (2, 0, "westie_tennis_run", 128, True, True),
            (0, 1, "westie_tennis_swing", 128, True, False),
            (1, 1, "westie_tennis_dive", 128, False, False),
            (2, 1, "westie_victory", 128, True, False),
        ],
        out_dir,
    )

    slice_grid_3x2(
        raw_dir / "tennis_player_props_sheet.png",
        [
            (0, 0, "player_ready", 128, True, True),
            (1, 0, "player_run", 128, True, True),
            (2, 0, "player_swing", 128, True, False),
            (0, 1, "tennis_ball", 64, False, False),
            (1, 1, "bone_treat", 64, False, False),
            (2, 1, "badge_icon", 128, False, False),
        ],
        out_dir,
    )

    # Also export a crisp 512x512 AppIcon PNG from the Westie tennis badge cell
    props_sheet = Image.open(raw_dir / "tennis_player_props_sheet.png").convert("RGBA")
    pw, ph = props_sheet.size
    badge_cell = props_sheet.crop((2 * (pw // 3), ph // 2, pw, ph))
    app_icon, _ = clean_and_normalize_sprite(badge_cell, canvas_size=512, bottom_align=False, padding=24)
    app_icon_path = out_dir.parent / "AppIcon.png"
    app_icon.save(app_icon_path)
    print(f"[ICON] Saved {app_icon_path.name} (512x512)")


if __name__ == "__main__":
    main()
